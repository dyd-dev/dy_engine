enum class SceneAssetRoot { External, Repository };

// This records discovery, not a successful import or a platform qualification.
// Candidate entries become available only when their complete package is installed.
enum class SceneAssetAvailability { Inventoried, Candidate, ConversionRequired };

struct SceneAsset
{
    const char* id;
    const char* name;
    const char* category;
    SceneAssetRoot root;
    const char* relativePath;
    // Relative to the same root; empty means the viewer's default environment.
    const char* environmentPath;
    const char* format;
    const char* workload;
    const char* license;
    const char* sourceUrl;
    const char* platformNotes;
    bool animated;
    SceneAssetAvailability availability;
};

constexpr const char* AssetAvailabilityName(SceneAssetAvailability availability)
{
    switch(availability)
    {
    case SceneAssetAvailability::Inventoried: return "Inventoried; not measured";
    case SceneAssetAvailability::Candidate: return "Candidate; install separately";
    case SceneAssetAvailability::ConversionRequired: return "Source conversion required";
    }
    return "Unknown";
}

constexpr bool CatalogCanLoadModel(const SceneAsset& asset)
{
    const std::string_view format(asset.format);
    return asset.availability != SceneAssetAvailability::ConversionRequired &&
        (format == "GLB" || format == "glTF" || format == "FBX");
}

