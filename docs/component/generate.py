    def dyf_detail_html(self, entry, fallback_text=""):
        # RHI's detail renderer omits examples; dyf keeps them with their contracts.
        content = '<p>' + self.rich(entry.get("summary") or fallback_text or NO_COMMENT) + '</p>'
        content += ''.join('<p>' + self.rich(paragraph) + '</p>' for paragraph in entry.get("remarks", []))
        if entry.get("parameters"):
            content += '<h3>매개 변수</h3>' + self.table(
                ["이름", "설명"], [[self.rich(name), self.rich(text)] for name, text in entry["parameters"]])
        if entry.get("returns"):
            content += '<h3>반환값</h3><p>' + self.rich(entry["returns"]) + '</p>'
        if entry.get("example"):
            content += '<h3>사용 예제</h3>' + self.code(entry["example"])
        return content

