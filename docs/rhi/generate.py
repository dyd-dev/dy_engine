        if params:
            toc.append(("parameters", "매개변수"))
            content += '<section id="parameters"><h2>매개변수</h2><dl class="parameters">' + "".join(f'<dt><code>{escape(p)}</code></dt><dd>{self.rich(desc)}</dd>' for p, desc in params.items()) + '</dl></section>'
