    def source_link(self, header, line=1):
        return f'header-{Path(header).stem.lower()}.html#L{line}'

    def symbol_page(self, key, decl):
        doc = self.doc(decl.name)
        toc = [("syntax", "구문")]
        content = f'<section id="syntax"><h2>구문</h2>{self.code(decl.syntax)}</section>'
        fields = [m for m in decl.members if m.kind in ("field", "value")]
        methods = [m for m in decl.members if m.kind == "method"]
        if fields:
            label = "상수" if decl.kind == "enum" else "멤버 변수"
            field_anchor = "fields" if methods else "members"
            toc.append((field_anchor, label))
            rows = []
            for member in fields:
                detail = self.member_doc(decl, member)
                value = member.value if member.kind == "value" else member.syntax
                rows.append([f'<code id="{slug(member.name)}">{escape(member.name)}</code>', f'<code>{escape(value)}</code>', self.rich(detail["summary"])])
            content += f'<section id="{field_anchor}"><h2>{label}</h2>{self.table(["이름", "값" if decl.kind == "enum" else "선언과 기본값", "설명"], rows)}</section>'
        if methods:
            toc.append(("members", "멤버 함수"))
            unique = list(dict.fromkeys(m.name for m in methods))
            content += '<section id="members"><h2>멤버 함수</h2>' + self.table(["이름", "설명"], [[f'<a href="#{slug(name)}"><code>{escape(name)}</code></a>', self.rich(self.member_doc(decl, next(m for m in methods if m.name == name))["summary"])] for name in unique]) + '</section>'
        params = doc.get("params", {})
        returns = doc.get("returns")
        if decl.name.startswith("operator") and decl.kind == "function":
            params = {"left": "왼쪽 비트 플래그 값입니다. 대입 연산에서는 이 값을 갱신합니다.", "right": "오른쪽 비트 플래그 값입니다."}
